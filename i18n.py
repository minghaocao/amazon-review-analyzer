def normalize_language(language: object = None) -> str:
    """Return a supported language code, falling back to the configured default."""

    if isinstance(language, str):
        value = language.strip()
        if value in TRANSLATIONS:
            return value
        if value in SUPPORTED_LANGUAGES:
            return SUPPORTED_LANGUAGES[value]
        normalized = value.casefold().replace("_", "-")
        if normalized in {"zh", "zh-cn", "zh-hans", "chinese", "简体中文", "中文"}:
            return "zh"
        if normalized in {"en", "en-us", "en-gb", "english"}:
            return "en"
    return DEFAULT_LANGUAGE if DEFAULT_LANGUAGE in TRANSLATIONS else "en"


def t(key: str, language: object = None, **values: object) -> str:
    """Resolve one display string with Chinese → English → key fallback."""

    lang = normalize_language(language)
    template = TRANSLATIONS.get(lang, {}).get(key)
    if template is None:
        template = TRANSLATIONS["en"].get(key, key)
    if not values:
        return template
    try:
        return template.format(**values)
    except (KeyError, ValueError, IndexError):
        # A display-formatting mistake must not break the dashboard. Tests guard
        # placeholder parity across languages; this remains a safe runtime fallback.
        return template


def t_count(
    singular_key: str,
    plural_key: str,
    count: int,
    language: object = None,
    **values: object,
) -> str:
    """Render basic English plurality; Chinese uses the singular template."""

    lang = normalize_language(language)
    key = singular_key if lang == "zh" or count == 1 else plural_key
    return t(key, lang, count=count, **values)


def localized_error_message(
    error: object,
    translation_key: str,
    language: object = None,
) -> str:
    """Keep established English diagnostics and show friendly Chinese copy."""

    lang = normalize_language(language)
    return str(error) if lang == "en" else t(translation_key, lang)


def display_duration(seconds: float | None, language: object = None) -> str:
    """Format one display duration without changing stored numeric timing data."""

    lang = normalize_language(language)
    if seconds is None:
        return t("runtime.estimating", lang)
    value = max(0, int(round(seconds)))
    hours, remainder = divmod(value, 3600)
    minutes, secs = divmod(remainder, 60)
    if lang == "zh":
        if hours:
            return f"{hours} 小时 {minutes} 分钟"
        if minutes:
            return f"{minutes} 分钟 {secs} 秒"
        return f"{secs} 秒"
    if hours:
        return f"{hours}h {minutes}m"
    if minutes:
        return f"{minutes}m {secs}s"
    return f"{secs}s"


