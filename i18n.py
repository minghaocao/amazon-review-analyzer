def _record_aspects(records: object) -> list[str]:
    if not isinstance(records, Sequence) or isinstance(records, (str, bytes)):
        return []
    result: list[str] = []
    for record in records[:2]:
        if isinstance(record, Mapping):
            aspect = str(record.get("aspect", "")).strip()
            if aspect:
                result.append(aspect)
    return result


def _join_aspects(aspects: Sequence[str], language: str) -> str:
    names = [display_aspect(aspect, language) for aspect in aspects]
    if language == "zh":
        return "、".join(names)
    if len(names) < 2:
        return "".join(names)
    return " and ".join(names)


def localized_executive_summary(
    intelligence: Mapping[str, Any] | None,
    language: object = None,
) -> str:
    """Build a localized summary from the same deterministic BI records."""

    lang = normalize_language(language)
    source = intelligence if isinstance(intelligence, Mapping) else {}
    strengths = _record_aspects(source.get("selling_points"))
    issues = _record_aspects(source.get("pain_points"))
    if not strengths and not issues:
        return t("summary.no_signals", lang)
    sample = source.get("sample_level")
    if isinstance(sample, Mapping):
        sample_key = str(sample.get("key", ""))
    else:
        sample_key = str(sample or "")
    prefix_key = {
        "early_signals": "summary.early_prefix",
        "limited_sample": "summary.limited_prefix",
        "full_insight": "summary.full_prefix",
    }.get(sample_key, "summary.full_prefix")
    prefix = t(prefix_key, lang)
    strengths_text = _join_aspects(strengths, lang)
    issues_text = _join_aspects(issues, lang)
    if strengths and issues:
        return t(
            "summary.strengths_and_issues",
            lang,
            prefix=prefix,
            strengths=strengths_text,
            issues=issues_text,
        )
    if strengths:
        return t(
            "summary.strengths_only",
            lang,
            prefix=prefix,
            strengths=strengths_text,
        )
    return t(
        "summary.issues_only",
        lang,
        prefix=prefix,
        issues=issues_text,
    )


