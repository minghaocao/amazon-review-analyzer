def localized_comparison_summary(
    comparison: Mapping[str, Any] | None,
    language: object = None,
) -> str:
    """Build Step 13's deterministic bilingual executive summary.

    Only the compact canonical facts already stored by the comparison engine
    are used.  No generated prose, review text, or customer Evidence is
    translated, and ``comparison`` is never mutated.
    """

    source = comparison if isinstance(comparison, Mapping) else {}
    lang = normalize_language(language)
    product_a = source.get("product_a")
    product_b = source.get("product_b")
    a_metadata = product_a if isinstance(product_a, Mapping) else {}
    b_metadata = product_b if isinstance(product_b, Mapping) else {}
    a_name = str(a_metadata.get("product_name") or t("comparison.product_a", lang))
    b_name = str(b_metadata.get("product_name") or t("comparison.product_b", lang))

    facts = source.get("executive_summary")
    facts = facts if isinstance(facts, Mapping) else {}
    a_aspects = _record_aspects(
        [{"aspect": item} for item in facts.get("product_a_advantages", [])]
        if isinstance(facts.get("product_a_advantages"), Sequence)
        and not isinstance(facts.get("product_a_advantages"), (str, bytes))
        else []
    )
    b_aspects = _record_aspects(
        [{"aspect": item} for item in facts.get("product_b_advantages", [])]
        if isinstance(facts.get("product_b_advantages"), Sequence)
        and not isinstance(facts.get("product_b_advantages"), (str, bytes))
        else []
    )
    pain_aspects = _record_aspects(
        [{"aspect": item} for item in facts.get("shared_pain_points", [])]
        if isinstance(facts.get("shared_pain_points"), Sequence)
        and not isinstance(facts.get("shared_pain_points"), (str, bytes))
        else []
    )

    if a_aspects and b_aspects:
        summary = t(
            "comparison.summary.advantages_and_weaknesses",
            lang,
            a_name=a_name,
            b_name=b_name,
            a_aspects=_join_aspects(a_aspects, lang),
            b_aspects=_join_aspects(b_aspects, lang),
        )
    elif a_aspects:
        summary = t(
            "comparison.summary.advantages_only",
            lang,
            a_name=a_name,
            a_aspects=_join_aspects(a_aspects, lang),
        )
    elif b_aspects:
        summary = t(
            "comparison.summary.weaknesses_only",
            lang,
            a_name=a_name,
            b_name=b_name,
            b_aspects=_join_aspects(b_aspects, lang),
        )
    else:
        summary = t("comparison.summary.no_supported_signals", lang)

    if pain_aspects:
        pain = t(
            "comparison.summary.shared_pain",
            lang,
            pain_aspects=_join_aspects(pain_aspects, lang),
        ).strip()
        separator = " " if lang == "en" else ""
        summary = f"{summary.rstrip()}{separator}{pain}"
    return summary


